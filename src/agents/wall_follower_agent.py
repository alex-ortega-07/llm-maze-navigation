from typing import Literal

from agents.agent import Action, Agent, Observation

# Direction obtained by turning right / left from each heading
RIGHT_OF = {Action.UP: Action.RIGHT, Action.RIGHT: Action.DOWN, Action.DOWN: Action.LEFT, Action.LEFT: Action.UP}
LEFT_OF = {turned: heading for heading, turned in RIGHT_OF.items()}
BEHIND = {Action.UP: Action.DOWN, Action.DOWN: Action.UP, Action.LEFT: Action.RIGHT, Action.RIGHT: Action.LEFT}


class WallFollowerAgent(Agent):
    """Follows one wall of the maze (the right-hand or left-hand rule).

    At every step, relative to the direction it is facing, it tries in this order:
        1. turn to its preferred side (right for the right-hand rule),
        2. go straight,
        3. turn to the other side,
        4. go back.

    In a maze without cycles (a "perfect" maze, like the ones generated by
    Prim's algorithm) every wall is connected to the outer wall, so following
    it always leads to the exit. In a maze with cycles it can loop forever
    around an inner wall.
    """

    def __init__(self, hand: Literal["right", "left"] = "right", name: str | None = None) -> None:
        super().__init__(name or f"WallFollowerAgent({hand})")
        self.hand = hand
        self.heading: Action | None = None

    def reset(self) -> None:
        self.heading = None

    def act(self, obs: Observation) -> Action:
        valid = obs["valid_actions"]

        # At the start the agent does not know which way it is facing: take the first open direction
        if self.heading is None:
            self.heading = valid[0]

        preferred = RIGHT_OF if self.hand == "right" else LEFT_OF
        other = LEFT_OF if self.hand == "right" else RIGHT_OF

        for candidate in (preferred[self.heading], self.heading, other[self.heading], BEHIND[self.heading]):
            if candidate in valid:
                self.heading = candidate
                return candidate

        # Only reachable if no move is possible (a cell closed on all four sides)
        return self.heading
